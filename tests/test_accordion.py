from pages.main_page import MainPage
import pytest
import allure
from pages.main_page import MainPage

class TestAccordion:

    @allure.title("Проверка выпадающего списка 'Вопросы о важном'")
    @allure.description("Проверяем, что при клике на стрелочку открывается соответствующий текст ответа")
    @pytest.mark.parametrize(
        "index, expected_text",
        [
            (0, "Сутки — 400 рублей. Оплата курьеру — наличными или картой."),
            (1, "Пока что у нас так: один заказ — один самокат. Если хотите покататься с друзьями — можете оформить несколько заказов подряд."),
            (2, "Допустим, вы оформляете заказ на 8 мая. Мы привозим самокат 8 мая в течение дня. Отсчёт времени аренды начинается с момента, когда вы оплатите заказ курьеру. Если самокат нужен живём на сутки, вернёте его 9 мая в это же время."),
            (3, "Только сегодня и именно сейчас. Пока выкатываете один самокат, второй ждёт вас в коробке."),
            (4, "Если мы везем самокат к 20:00, то вернем его к 20:00 следующего дня. Курьер позвонит за час до прибытия."),
            (5, "Самокат приезжает к вам с полной зарядкой. Этого хватает на восемь часов беспрерывной езды — то есть вполне на весь день."),
            (6, "Да, пока самокат не привезли, вы можете отменить заказ. После оплаты отмена невозможна."),
            (7, "Да, мы возим за МКАД, но в пределах 15 км. Доставка бесплатная.")
        ]
    )
    def test_accordion_questions_and_answers(self, driver, index, expected_text):
        main_page = MainPage(driver)
        
        driver.get("https://praktikum-services.ru")
        
        main_page.accept_cookies()
        
        main_page.click_question(index)
        
        actual_text = main_page.get_answer_text(index)
        
        assert actual_text == expected_text, f"Текст ответа под индексом {index} не совпадает!"
        